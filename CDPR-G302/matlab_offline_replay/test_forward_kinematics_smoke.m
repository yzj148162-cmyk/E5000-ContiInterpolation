function test_forward_kinematics_smoke
% Deterministic no-file smoke test for transform order and the 8-cable solver.
cfg.geometry.base_anchor_global_mm = [ ...
 -1359.7418  1227.8132 1794.6246; -1223.4262  1359.1054    2.4284; ...
  1364.2568  1227.3729 1787.7869;  1225.0618  1361.8618   -2.3197; ...
  1366.5515 -1220.2830 1790.4813;  1222.2815 -1360.0458    2.3377; ...
 -1354.5389 -1220.1533 1793.0807; -1223.9172 -1360.9214   -2.4464];
cfg.geometry.platform_attachment_local_mm_by_end = [ ...
 -235.61   76.55 -123.87; -145.62  200.42  123.87; ...
  235.61   76.55 -123.87;  145.62  200.42  123.87; ...
  145.62 -200.42 -123.87;  235.61  -76.55  123.87; ...
 -145.62 -200.42 -123.87; -235.61  -76.55  123.87];
cfg.geometry.pulley_radius_mm = 0;
cfg.workspace = struct( ...
    'frame_minimum_mm',[-1400;-1400;-100], ...
    'frame_maximum_mm',[1400;1400;2670], ...
    'orientation_bounds_enabled',false, ...
    'orientation_minimum_rad',[-3.14;-3.14;-3.14], ...
    'orientation_maximum_rad',[3.14;3.14;3.14]);
target = [120 -80 650 0.025 -0.018 0.012];
lengths = cdpr_cable_lengths(target, cfg);
initial = target + [10 -8 6 0.005 -0.004 0.003];
solved = solve_forward_kinematics(lengths, initial, cfg);
poseError = norm(solved.pose-target);
fprintf('MATLAB FK smoke: success=%d, pose error=%.9g, RMS residual=%.9g mm\n', ...
    solved.success, poseError, solved.rmsResidualMm);
assert(solved.success && poseError < 1e-4, ...
    '八绳正运动学未能从扰动初值返回已知位姿。');
end
